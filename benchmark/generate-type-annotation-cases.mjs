import { writeFileSync } from "node:fs";
import path from "node:path";

const directory = path.join(import.meta.dirname, "cases/typed");
const header = "// Generated by benchmark/generate-type-annotation-cases.mjs.\n";

function write(name, imports, body, copies) {
	const code =
		header + imports + "\n\n" + Array.from({ length: copies }, () => body).join("\n\n");
	writeFileSync(path.join(directory, `${name}.ts`), `${code}\n`);
}

const readImport = 'import { read } from "./helpers.js";';
write("annotation-none", readImport, "{\n\tconst value = read();\n\tvoid value;\n}", 40);
write(
	"annotation-removals",
	readImport,
	"{\n\tconst value: string = read();\n\tvoid value;\n}",
	10,
);
write("annotation-dense", readImport, "{\n\tconst value: string = read();\n\tvoid value;\n}", 40);
write(
	"annotation-parameters",
	'import { run } from "./helpers.js";',
	"run((value: string) => value);",
	8,
);
write(
	"annotation-retained",
	'import type { TreeNode } from "./helpers.js";',
	`{
	function descend<T>(root: TreeNode<T>): T {
		let node: TreeNode<T> | undefined = root;
		let last = root.value;
		while (node !== undefined) {
			last = node.value;
			const left: TreeNode<T> | undefined = node.left;
			node = left;
		}
		return last;
	}
	void descend;
}`,
	8,
);
